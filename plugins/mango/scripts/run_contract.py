#!/usr/bin/env python3
"""RUN CONTRACT — write, validate, bind, and seed the DISCLOSURE list.

Stdlib only, no network. The contract is written by THIS script from agent-supplied values in a fixed
grammar, and parsed back before the run starts: if it does not parse, the run does not start.

What this script guarantees and what it does not:

  * GUARANTEED — the contract is well-formed and internally consistent: every condition carries a
    statement and a runnable check; the three floor conditions are present and are the shipped ones;
    the checks of TREE-COMPARISON and LOCAL-HEAD-PUSHED are GENERATED by this script from the header
    (`base`, `branch`, `remote`) and any other spelling is refused; no `${PLACEHOLDER}` survives past
    its binding phase.
  * NOT GUARANTEED — that any recorded value is TRUE. Machine-writing guarantees the grammar, not the
    facts. So every value that CAN be derived is derived by running a command and recording its real
    output; everything else is marked `agent-claim (unchecked)` and is carried into DISCLOSURE.

Subcommands
  write            <spec.json> [--repo DIR]   emit a contract, deriving every derivable value
  validate         <contract>  --phase t0|gate2|close|post-merge
  bind             <contract>  NAME=VALUE ...  --out FILE
  disclosure-seed  <contract>

Exit codes: 0 ok · 2 the contract does not parse / refuses to bind · 1 usage or I/O error.
"""

import json
import re
import shutil
import subprocess
import sys

GRAMMAR_VERSION = "RUN CONTRACT v1"

# The shell every condition check is written for. Named EXPLICITLY (never left to the host) so one
# check behaves the same on every machine: `/bin/sh` is dash on Debian and cmd.exe on Windows, and a
# check handed to the host's default silently means something different per host. NO_SHELL is the
# sentinel `sh` returns when that shell is not on PATH — a could-not-run, never a HOLDING/BROKEN.
SHELL = "bash"
NO_SHELL = "no-shell"

HEADER_KEYS = [
    "key",
    "started",
    "plugin-version",
    "plugin-path",
    "repo",
    "base",
    "branch",
    "remote",
    "merge-strategy",
    "reviewer",
    "challenger",
    "handover-authorisation",
    "call-ceiling",
    "per-call-estimate",
    "ceiling-source",
    "token-budget",
]

# Every condition declares these FIVE fields. `force-broken` / `force-holding` were mandatory grammar
# fields until v1.14.0; the forced-case positive control they fed is RETIRED, so they are no longer part
# of the grammar and a contract carrying either is REJECTED as an unknown field — never tolerated and
# silently ignored, which would leave a field nothing consumes looking like a live requirement.
CONDITION_KEYS = ["statement", "origin", "derived-by", "value", "check"]
RETIRED_CONDITION_KEYS = ("force-broken", "force-holding")

# The fixed floor — three conditions the agent may not author, may not rename, and may not drop.
FLOOR = {
    "PR-EXISTS": "the PR exists and its state is readable",
    "TREE-COMPARISON": "no commit landed on the branch beyond what the PR carries (tree comparison)",
    "LOCAL-HEAD-PUSHED": "nothing is stranded on this machine: local branch head == the remote's",
}

UNBOUND_RE = re.compile(r"UNBOUND \$\{[A-Z][A-Z0-9_]*\}")

# The header fields the generated floor checks are rendered from. They reach a shell, so each has a
# grammar: a ref name of plain characters, and `base` as `<branch>@<sha>` (derived by command at
# write time, never typed). Free-form `base` values (`main`, a bare sha, `main @ <sha>`) were all
# observed in field contracts; the generator cannot render a check from any of them.
REF_RE = re.compile(r"^[A-Za-z0-9._/-]+$")
BASE_RE = re.compile(r"^(?P<branch>[A-Za-z0-9._/-]+)@(?P<sha>[0-9a-f]{7,40})$")
# A bound path list: plain path tokens only (no shell metacharacters, no quoting).
PATH_TOKEN_RE = re.compile(r"^[A-Za-z0-9._/@+-]+$")
CHANGED_PATHS = "UNBOUND ${CHANGED_PATHS}"


def tree_check(base_branch, branch, remote, paths=CHANGED_PATHS):
    """The ONE spelling of TREE-COMPARISON: the remote's base against the remote's branch, on the
    approved change list. It is meaningful only after the merge — RECONCILE counts it `pending-merge`
    at close and runs it at `post-merge`. Both sides are the REMOTE's refs: a correction committed but
    never pushed is LOCAL-HEAD-PUSHED's case, not this one's."""
    return f"git diff --quiet {remote}/{base_branch} {remote}/{branch} -- {paths}"


def head_check(branch, remote):
    """The ONE spelling of LOCAL-HEAD-PUSHED: both refs resolved with `--verify` before comparing."""
    local, theirs = f"refs/heads/{branch}", f"refs/remotes/{remote}/{branch}"
    return (
        f"git rev-parse --verify -q {local} >/dev/null && "
        f"git rev-parse --verify -q {theirs} >/dev/null && "
        f'test "$(git rev-parse {local})" = "$(git rev-parse {theirs})"'
    )


def generated_checks(header):
    """{condition id: canonical check} for the generated floor, or ({}, reasons) when the header
    cannot render one."""
    reasons = []
    base = BASE_RE.match(header.get("base", ""))
    if not base:
        reasons.append(
            f"header 'base' must be `<branch>@<sha>` (derived by `run_contract.py write`), found "
            f"'{header.get('base', '')}' — the floor checks are rendered from it"
        )
    for key in ("branch", "remote"):
        if not REF_RE.match(header.get(key, "")):
            reasons.append(
                f"header '{key}' must be a plain ref name ([A-Za-z0-9._/-]), found "
                f"'{header.get(key, '')}' — the floor checks are rendered from it"
            )
    if reasons:
        return {}, reasons
    branch, remote = header["branch"], header["remote"]
    return {
        "TREE-COMPARISON": tree_check(base.group("branch"), branch, remote),
        "LOCAL-HEAD-PUSHED": head_check(branch, remote),
    }, []


def check_generated(header, conditions):
    """A generated floor check must be EXACTLY the rendered one (TREE-COMPARISON's path list may be
    bound). Any other spelling is refused, never silently corrected: twelve field contracts carried
    two meanings under one id, one of them a false HOLDING on the incident the condition exists for."""
    canon, reasons = generated_checks(header)
    if reasons:
        return reasons
    by_id = {c["id"]: c for c in conditions}
    head = by_id.get("LOCAL-HEAD-PUSHED")
    if head is not None and head["fields"].get("check", "") != canon["LOCAL-HEAD-PUSHED"]:
        reasons.append(
            "LOCAL-HEAD-PUSHED's check is GENERATED, not authored — expected exactly: "
            + canon["LOCAL-HEAD-PUSHED"]
        )
    tree = by_id.get("TREE-COMPARISON")
    if tree is not None:
        chk = tree["fields"].get("check", "")
        prefix = canon["TREE-COMPARISON"][: -len(CHANGED_PATHS)]
        paths = chk[len(prefix):] if chk.startswith(prefix) else None
        if paths is None or not (
            paths == CHANGED_PATHS
            or (paths.split() and all(PATH_TOKEN_RE.match(t) for t in paths.split()))
        ):
            reasons.append(
                "TREE-COMPARISON's check is GENERATED, not authored — expected exactly: "
                + canon["TREE-COMPARISON"]
                + " (the path list bound at Gate 2 from the approved change list, plain path tokens)"
            )
    return reasons
AGENT_CLAIM = "agent-claim (unchecked)"
CONDITION_ID_RE = re.compile(r"^[A-Z][A-Z0-9-]*$")


class ContractError(Exception):
    """The contract does not parse. Carries every reason, not just the first."""

    def __init__(self, reasons):
        self.reasons = reasons
        super().__init__("; ".join(reasons))


def sh(command, repo=None, timeout=120):
    """Run a shell command in an EXPLICIT, NAMED shell; return (status, output). Never raises.

    The command is invoked as `bash -c <command>` — never `shell=True`, which hands the choice of
    shell to the host (`/bin/sh`, i.e. dash on Debian, on Linux; cmd.exe on Windows). When the named
    shell is not on PATH the command is NOT run: `sh` returns the sentinel status `NO_SHELL`, and the
    caller reports could-not-run. A check that cannot run must never report holding.
    """
    shell = shutil.which(SHELL)
    if shell is None:
        return NO_SHELL, f"could-not-run: shell '{SHELL}' is not on PATH — the check was not run"
    try:
        # Invoke the ABSOLUTE path `which` resolved, never the bare name: a bare `bash` lets the OS
        # re-resolve it (on Windows the WindowsApps WSL alias shadows a real bash), which is exactly
        # the host-picks-the-shell defect this fix removes.
        proc = subprocess.run(
            [shell, "-c", command], cwd=repo, capture_output=True, text=True, timeout=timeout
        )
        return proc.returncode, (proc.stdout + proc.stderr).strip()
    except Exception as exc:  # noqa: BLE001 — a broken command is data, never a crash
        return 127, f"command did not run: {exc}"


# --------------------------------------------------------------------------- parse


def parse(text):
    """Parse a contract into (header, [conditions]). Raises ContractError with every reason."""
    reasons = []
    lines = [ln.strip() for ln in text.splitlines()]
    lines = [ln for ln in lines if ln and not ln.startswith("#")]
    if not lines:
        raise ContractError(["the contract is empty"])
    if lines[0] != GRAMMAR_VERSION:
        raise ContractError([f"line 1 must be exactly '{GRAMMAR_VERSION}', found '{lines[0]}'"])
    if lines[-1] != "END RUN CONTRACT":
        reasons.append("the contract must end with 'END RUN CONTRACT'")

    header = {}
    conditions = []
    current = None
    for raw in lines[1:]:
        if raw == "END RUN CONTRACT":
            if current is not None:
                reasons.append(f"CONDITION {current['id']} is not closed by 'END CONDITION'")
            continue
        if raw.startswith("CONDITION "):
            if current is not None:
                reasons.append(f"CONDITION {current['id']} is not closed by 'END CONDITION'")
            cid = raw[len("CONDITION "):].strip()
            if not CONDITION_ID_RE.match(cid):
                reasons.append(f"'{cid}' is not a valid CONDITION id (UPPER-KEBAB)")
            if any(c["id"] == cid for c in conditions):
                reasons.append(f"CONDITION {cid} is declared more than once")
            current = {"id": cid, "fields": {}}
            continue
        if raw == "END CONDITION":
            if current is None:
                reasons.append("'END CONDITION' with no open CONDITION")
                continue
            for key in CONDITION_KEYS:
                if key not in current["fields"]:
                    reasons.append(
                        f"CONDITION {current['id']} is missing the mandatory field '{key}'"
                    )
            conditions.append(current)
            current = None
            continue
        if ":" not in raw:
            reasons.append(f"line is neither a block marker nor a 'key: value' pair: '{raw}'")
            continue
        key, _, value = raw.partition(":")
        key = key.strip()
        value = value.strip()
        if current is None:
            if key not in HEADER_KEYS:
                reasons.append(f"unknown header key '{key}'")
            elif key in header:
                reasons.append(f"header key '{key}' appears more than once")
            else:
                header[key] = value
        else:
            if key in RETIRED_CONDITION_KEYS:
                reasons.append(
                    f"CONDITION {current['id']}: '{key}' is a RETIRED field — the forced-case "
                    "positive control was removed in v1.14.0 and nothing consumes it. Delete the "
                    "line; a contract carrying it is rejected, never silently ignored."
                )
            elif key not in CONDITION_KEYS:
                reasons.append(f"CONDITION {current['id']}: unknown field '{key}'")
            elif key in current["fields"]:
                reasons.append(f"CONDITION {current['id']}: field '{key}' appears more than once")
            else:
                current["fields"][key] = value

    for key in HEADER_KEYS:
        if key not in header:
            reasons.append(f"the header is missing '{key}'")
    if reasons:
        raise ContractError(reasons)
    return header, conditions


def check_floor(header, conditions):
    """The three floor conditions must be present, marked `origin: floor`, and shaped as shipped."""
    reasons = []
    by_id = {c["id"]: c for c in conditions}
    for cid, statement in FLOOR.items():
        cond = by_id.get(cid)
        if cond is None:
            reasons.append(f"floor condition {cid} is missing — the agent may not drop it")
            continue
        if cond["fields"].get("origin") != "floor":
            reasons.append(f"floor condition {cid} must be marked 'origin: floor'")
        if statement.split("(")[0].strip()[:12].lower() not in cond["fields"].get("statement", "").lower():
            reasons.append(
                f"floor condition {cid} does not state the shipped requirement: {statement}"
            )

    tree = by_id.get("TREE-COMPARISON")
    if tree is not None:
        chk = tree["fields"].get("check", "")
        if not UNBOUND_RE.search(chk):
            if "git diff" not in chk or "--quiet" not in chk:
                reasons.append(
                    "TREE-COMPARISON must be a TREE comparison — `git diff --quiet <base> <branch> "
                    "-- <paths>` — never a content grep for text named at t0"
                )
            if re.search(r"\bgrep\b", chk):
                reasons.append(
                    "TREE-COMPARISON must not grep for content: a post-merge correction is unnamed "
                    "at t0, so a grep returns HOLDING on the very incident this condition catches"
                )
            if re.search(r"merge-base|--is-ancestor", chk):
                reasons.append(
                    "TREE-COMPARISON must not use an ancestry predicate (`merge-base --is-ancestor`) "
                    "— it is a false-red under a squash merge"
                )
    head = by_id.get("LOCAL-HEAD-PUSHED")
    if head is not None:
        chk = head["fields"].get("check", "")
        if not UNBOUND_RE.search(chk):
            if "rev-parse" not in chk:
                reasons.append(
                    "LOCAL-HEAD-PUSHED must compare the two heads with `git rev-parse` "
                    "(local branch head vs the remote's)"
                )
            remote = header.get("remote", "origin")
            if f"{remote}/" not in chk:
                reasons.append(
                    f"LOCAL-HEAD-PUSHED must name the remote ref ({remote}/<branch>) — a local-only "
                    "comparison cannot see what never left this machine"
                )
            if "--verify" not in chk:
                reasons.append(
                    "LOCAL-HEAD-PUSHED must resolve each ref with `git rev-parse --verify` before "
                    "comparing: when BOTH lookups fail, a bare `test \"$(...)\" = \"$(...)\"` "
                    "compares empty to empty and reports HOLDING — a false green exactly where the "
                    "branch does not exist"
                )
    pr = by_id.get("PR-EXISTS")
    if pr is not None:
        if pr["fields"].get("check", "") in ("", AGENT_CLAIM):
            reasons.append(
                "PR-EXISTS must carry a real command whose exit status is the verdict — RECONCILE "
                "runs it; an agent's word that the PR exists is not the condition"
            )
    return reasons


def check_phase(conditions, phase):
    """Phase rules. `t0` tolerates UNBOUND placeholders; `gate2` and `close` refuse every survivor."""
    reasons = []
    for cond in conditions:
        fields = cond["fields"]
        if UNBOUND_RE.search(fields.get("statement", "")):
            reasons.append(f"CONDITION {cond['id']}: 'statement' may never be UNBOUND")
        if fields.get("origin") not in ("floor", "agent"):
            reasons.append(f"CONDITION {cond['id']}: 'origin' must be 'floor' or 'agent'")
        for key in ("value", "check"):
            val = fields.get(key, "")
            if "UNBOUND" in val and not UNBOUND_RE.search(val):
                reasons.append(
                    f"CONDITION {cond['id']}: '{key}' says UNBOUND but names no ${{PLACEHOLDER}}"
                )
            if phase in ("gate2", "close", "post-merge") and UNBOUND_RE.search(val):
                reasons.append(
                    f"CONDITION {cond['id']}: '{key}' is still UNBOUND at {phase} — "
                    "re-validation refuses a surviving placeholder"
                )
    return reasons


def validate(text, phase):
    """Full validation. Returns the parsed (header, conditions) or raises ContractError."""
    header, conditions = parse(text)
    reasons = (check_floor(header, conditions) + check_generated(header, conditions)
               + check_phase(conditions, phase))
    for seat in ("reviewer", "challenger"):
        if header.get(seat) not in ("on", "off"):
            reasons.append(f"header '{seat}' must be exactly 'on' or 'off'")
    if not header.get("handover-authorisation", "").strip():
        reasons.append(
            "header 'handover-authorisation' is empty — the run performs two outward actions with "
            "nobody awake (push the branch, open the PR) and must record the explicit authorisation "
            "naming exactly those two. Without it the run does not start."
        )
    ceiling = header.get("call-ceiling", "")
    if ceiling != "unknown" and not re.match(r"^\d+$", ceiling):
        reasons.append("header 'call-ceiling' must be an integer or the literal 'unknown'")
    if reasons:
        raise ContractError(reasons)
    return header, conditions


# --------------------------------------------------------------------------- write


def render(header, conditions):
    out = [GRAMMAR_VERSION]
    for key in HEADER_KEYS:
        out.append(f"  {key}: {header.get(key, '')}")
    for cond in conditions:
        out.append(f"  CONDITION {cond['id']}")
        for key in CONDITION_KEYS:
            out.append(f"    {key}: {cond['fields'].get(key, '')}")
        out.append("  END CONDITION")
    out.append("END RUN CONTRACT")
    return "\n".join(out) + "\n"


def derive_base(value, remote, repo=None):
    """`base` as `<branch>@<sha>`, the sha DERIVED by `git rev-parse` — never typed. Accepts the branch
    alone or `<branch>@<sha>`; a supplied sha that disagrees with the repo is refused (a wrong fact in
    the right format is still a wrong fact)."""
    raw = value.replace(" ", "")
    branch, _, given = raw.partition("@")
    if not REF_RE.match(branch):
        raise ContractError([f"spec 'base' must name the default branch (optionally @<sha>), found '{value}'"])
    sha = ""
    for ref in (branch, f"{remote}/{branch}"):
        status, out = sh(f"git rev-parse --verify -q {ref}^{{commit}}", repo=repo)
        if status == 0 and out.strip():
            sha = out.strip().splitlines()[0]
            break
    if not sha:
        raise ContractError([f"base branch '{branch}' does not resolve in the repo — cannot derive `base`"])
    if given and not sha.startswith(given):
        raise ContractError([f"spec 'base' says {branch}@{given} but the repo says {branch}@{sha}"])
    return f"{branch}@{sha}"


def write(spec, repo=None):
    """Build a contract from an agent-supplied spec, DERIVING every derivable value by command."""
    header = {key: str(spec.get(key, "")) for key in HEADER_KEYS}
    header["base"] = derive_base(header.get("base", ""), header.get("remote", ""), repo)
    canon, reasons = generated_checks(header)
    if reasons:
        raise ContractError(reasons)
    conditions = []
    for raw in spec.get("conditions", []):
        fields = {key: str(raw.get(key, "")) for key in CONDITION_KEYS}
        cid = str(raw.get("id", ""))
        if cid in canon:
            if fields["check"] and fields["check"] != canon[cid]:
                raise ContractError([
                    f"{cid}'s check is GENERATED by this script, not authored — omit it from the "
                    f"spec. Supplied: {fields['check']}  Generated: {canon[cid]}"
                ])
            fields["check"] = canon[cid]
            fields["statement"] = fields["statement"] or FLOOR[cid]
            fields["origin"] = fields["origin"] or "floor"
            if not fields["derived-by"]:
                fields["derived-by"] = (
                    f"git rev-parse --verify -q {header['remote']}/{BASE_RE.match(header['base']).group('branch')}"
                    if cid == "TREE-COMPARISON" else "git rev-parse HEAD"
                )
        derived_by = fields.get("derived-by", "")
        if derived_by and derived_by != AGENT_CLAIM and not UNBOUND_RE.search(derived_by):
            status, output = sh(derived_by, repo=repo)
            first = output.splitlines()[0] if output.splitlines() else ""
            fields["value"] = f"{first} (exit {status})"
        conditions.append({"id": cid, "fields": fields})

    present = {c["id"] for c in conditions}
    for cid in FLOOR:
        if cid not in present:
            raise ContractError(
                [f"floor condition {cid} is missing from the spec — it is shipped, not authored"]
            )
    return render(header, conditions)


# --------------------------------------------------------------------------- bind


def bind(text, bindings, phase="gate2"):
    """Substitute `UNBOUND ${NAME}` → value, then RE-VALIDATE and refuse every survivor."""
    bound = text
    for name, value in bindings.items():
        bound = bound.replace("UNBOUND ${%s}" % name, value)
    validate(bound, phase)  # raises on any survivor
    return bound


# --------------------------------------------------------------------------- disclosure


def disclosure_seed(header, conditions, contract_path="<contract>"):
    """The machine-writable floor of DISCLOSURE. Everything else only the agent knows."""
    out = ["DISCLOSURE"]
    # Line one records BOTH independent eyes, SEPARATELY. Waiving review is two decisions, not one:
    # a morning reader must be able to tell "clean, nobody looked" from "clean, the blind reviewer
    # looked". Collapsing them into one state loses exactly that distinction.
    reviewer, challenger = header.get("reviewer", ""), header.get("challenger", "")
    out.append(
        "  1a. REVIEWER: " + (
            "OFF — waived by `--no-reviewer`. No rule-book-grounded review of the diff ran; "
            "a clean result below carries no reviewer finding because none was sought."
            if reviewer == "off" else
            "ON — enabled for this run. Whether it ran is the review phase's record, not this line: a run "
            "that stopped before review ran no reviewer."))
    out.append(
        "  1b. CHALLENGER: " + (
            "OFF — waived by `--no-challenger`. Nothing independent re-derived the requirements from "
            "the raw ticket. A clean result below is not evidence of independence."
            if challenger == "off" else
            "ON — enabled for this run. Whether it ran is the review phase's record, not this line: a run "
            "that stopped before review ran no challenger."))
    if reviewer == "off" and challenger == "off":
        out.append(
            "      BOTH SEATS OFF — nothing but the author looked at this diff. This is recorded, "
            "not refused: the flag plus this line is the mechanism.")
    claims = [c for c in conditions if c["fields"].get("derived-by") == AGENT_CLAIM]
    out.append(f"  2. UNCHECKED AGENT CLAIMS: {len(claims)} — no command derived these values.")
    for cond in claims:
        out.append(f"       - {cond['id']}: {cond['fields'].get('value', '')}")
    if header.get("call-ceiling") == "unknown":
        out.append("  3. BUDGET: call-count ceiling unknown — no ledger history for this tier.")
    else:
        out.append(
            f"  3. BUDGET: call-count ceiling {header.get('call-ceiling')} "
            f"(proxy, per-call estimate {header.get('per-call-estimate')}, "
            f"source: {header.get('ceiling-source')}) — a proxy, not a measurement."
        )
    out.append(
        "  3b. POST-MERGE: TREE-COMPARISON is NOT verified by this run — it has meaning only once the "
        "PR is merged, so RECONCILE at close counts it `pending-merge`, never holding. After merging, "
        f"run: git fetch {header.get('remote', 'origin')} && python3 "
        f"{header.get('plugin-path', '<mango>')}/scripts/reconcile.py run {contract_path} "
        f"--phase post-merge --repo {header.get('repo', '.')}"
    )
    out.append(
        "  4. This list is the ONE artifact nothing can check: only the agent knows what it chose "
        "not to verify. A near-empty list on a long run is a reason to distrust the run, not to "
        "trust it. Every line below this one is appended by the agent."
    )
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- cli


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 1
    cmd = argv[1]
    args = argv[2:]

    def opt(name, default=None):
        return args[args.index(name) + 1] if name in args else default

    try:
        if cmd == "write":
            spec = json.loads(open(args[0], encoding="utf-8").read())
            sys.stdout.write(write(spec, repo=opt("--repo")))
            return 0
        if cmd == "validate":
            text = open(args[0], encoding="utf-8").read()
            phase = opt("--phase", "t0")
            validate(text, phase)
            print(f"RUN CONTRACT: parses at phase {phase}")
            return 0
        if cmd == "bind":
            text = open(args[0], encoding="utf-8").read()
            bindings = dict(
                a.split("=", 1) for a in args[1:] if "=" in a and not a.startswith("--")
            )
            bound = bind(text, bindings, opt("--phase", "gate2"))
            out = opt("--out")
            if out:
                open(out, "w", encoding="utf-8").write(bound)
            else:
                sys.stdout.write(bound)
            return 0
        if cmd == "disclosure-seed":
            text = open(args[0], encoding="utf-8").read()
            header, conditions = parse(text)
            sys.stdout.write(disclosure_seed(header, conditions, contract_path=args[0]))
            return 0
    except ContractError as exc:
        print("RUN CONTRACT: DOES NOT PARSE — the run does not start.")
        for reason in exc.reasons:
            print(f"  - {reason}")
        return 2
    except OSError as exc:
        print(f"run_contract: {exc}")
        return 1
    print(f"run_contract: unknown subcommand '{cmd}'")
    return 1


if __name__ == "__main__":
    # Output is UTF-8 whatever the console's code page: the grammars carry ≥ and —, which a cp1252
    # console cannot encode, and a crash there would read as a checker that never ran.
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv))
