#!/usr/bin/env python3
"""gen_reference.py — generate the reference pages from their sources of truth.

  docs/reference/config.md  ← plugins/mango/config/harness.example.json (keys, sections, `//<key>` notes)
  docs/reference/lines.md   ← plugins/mango/scripts/check_lines.py GRAMMARS (the counted-line registry)

Usage: python3 scripts/gen_reference.py            write both pages
       python3 scripts/gen_reference.py --check    compare only; never writes
Exit codes: 0 written / up to date · 2 a page is stale, or a config key has no `//<key>` note · 1 usage.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "mango"
EXAMPLE = PLUGIN / "config" / "harness.example.json"
PAGES = {"config": ROOT / "docs" / "reference" / "config.md", "lines": ROOT / "docs" / "reference" / "lines.md"}
HEADER = "<!-- GENERATED by scripts/gen_reference.py — do not edit by hand; edit the source and regenerate. -->\n"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def example_value(value):
    if isinstance(value, dict):
        return "object"
    if isinstance(value, list):
        return f"`{cell(json.dumps(value, ensure_ascii=False))}`" if len(json.dumps(value)) <= 60 else "array"
    return f"`{cell(json.dumps(value, ensure_ascii=False))}`"


def config_page():
    data = json.loads(EXAMPLE.read_text(encoding="utf-8"))
    missing, rows, section = [], [], ""
    for key, value in data.items():
        if key.startswith("//== "):
            section = key[5:].split(" ")[0].strip("= ").capitalize()
            continue
        if key.startswith("//"):
            continue
        note = data.get("//" + key)
        if note is None:
            missing.append(key)
            note = ""
        rows.append(f"| `{key}` | {section} | {example_value(value)} | {cell(note)} |")
    page = (HEADER + "# Config keys reference\n\n"
            "> **In 30 seconds.** Every top-level key of `.harness.json`. Look up, don't read through. Source of\n"
            "> truth: [`harness.example.json`](../../plugins/mango/config/harness.example.json) — if this page and it\n"
            "> disagree, it wins. Start from `config/harness.minimal.json` for a first ticket.\n\n"
            "| Key | Section | Example value | Meaning |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")
    return page, missing


def lines_page():
    sys.path.insert(0, str(PLUGIN / "scripts"))
    import check_lines as cl                                   # noqa: PLC0415 - loaded on demand
    rows = []
    for token in sorted(cl.GRAMMARS):
        spec = cl.GRAMMARS[token]
        at = spec.get("required_at") or ("epic path" if spec.get("epic_required") else "conditional")
        if spec.get("protocol"):
            at += f" (`PROTOCOL: {spec['protocol']}` docs)"
        rows.append(f"| `{token}` | {cell(spec['emitter'])} | {cell(at)} | `{cell(spec['canonical'])}` |")
    page = (HEADER + "# Counted lines reference\n\n"
            "> **In 30 seconds.** Every counted line mango ships, with its one canonical grammar. Look up, don't\n"
            "> read through. Source of truth: `python3 plugins/mango/scripts/check_lines.py grammars` — if this\n"
            "> page and it disagree, it wins.\n\n"
            "| Line | Emitted by | Required at | Canonical form |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")
    return page, []


def generate():
    """{name: (path, text, problems)} for every reference page."""
    out = {}
    for name, build in (("config", config_page), ("lines", lines_page)):
        text, missing = build()
        out[name] = (PAGES[name], text, [f"harness.example.json key `{k}` has no `//{k}` note" for k in missing])
    return out


def stale(path, text):
    return not path.exists() or path.read_text(encoding="utf-8") != text


def main(argv):
    args = argv[1:]
    if args not in ([], ["--check"]):
        print(__doc__)
        return 1
    status = 0
    for name, (path, text, problems) in generate().items():
        rel = path.relative_to(ROOT).as_posix()
        for problem in problems:
            print(f"gen_reference: {problem}")
            status = 2
        if args == ["--check"]:
            if stale(path, text):
                print(f"gen_reference: {rel} is stale — run `python3 scripts/gen_reference.py`")
                status = 2
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"gen_reference: wrote {rel}")
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv))
